// Writes docs/detection-eval.md from trained tiers and evaluation rows.
import { writeFile } from 'node:fs/promises';
import { probability, type Detector } from '../../src/shared/detect/model.ts';
import { auroc, type Row } from './fit.ts';
import type { TierName } from './train.ts';

interface Input {
  readonly models: Readonly<Record<TierName, Detector>>;
  /** Fit without the held-out rows, for scoring them honestly. */
  readonly heldModels: Readonly<Record<TierName, Detector>>;
  readonly evals: Readonly<Record<string, readonly Row[]>>;
  readonly chosen: Readonly<Record<TierName, string>>;
  readonly trainCount: number;
  readonly ensembleCount: number;
}

const TIERS: readonly TierName[] = ['instant', 'fast', 'classifier', 'full'];
const SHOWN: readonly TierName[] = ['fast', 'classifier', 'full'];
const pct = (x: number | null) => (x === null ? '–' : `${(100 * x).toFixed(1)}%`);
const rate = (xs: readonly boolean[]) => (xs.length ? xs.filter(Boolean).length / xs.length : null);

const BASELINES: Readonly<Record<string, (r: Row) => number>> = {
  'Rules only (v0.1)': (r) => r.features.rule_staging! + r.features.rule_generic! + r.features.rule_structure!,
  'TMR classifier alone': (r) => r.features.cls_logit!,
  'Binoculars alone': (r) => -r.features.binoculars!,
};

export async function writeReport({ models, heldModels, evals, chosen, trainCount, ensembleCount }: Input): Promise<void> {
  /** "share at 80+ / share at 60+" for a group of rows. */
  const both = (t: TierName, rows: readonly Row[]) => {
    const p = rows.map((r) => probability(models[t], r.features));
    return `${pct(rate(p.map((x) => x >= models[t].aiAt)))} / ${pct(rate(p.map((x) => x >= models[t].leanAt)))}`;
  };
  const lines: string[] = [
    '# Detection evaluation',
    '',
    `Generated by \`scripts/detector/train.ts\` on ${new Date().toISOString().slice(0, 10)}. Every number comes from the shipped feature code and models, run in Node through the same Transformers.js code the extension uses. Training used ${trainCount} texts: 2025 chatbot replies from LMArena and WildChat (GPT, Gemini, Claude, Grok, DeepSeek, Llama, Qwen, Mistral), Claude-written business text including 300 pieces told to pass as human, and human text from English learners (ELL Stack Exchange), technical answers (Unix & Linux Stack Exchange), Enron email, MAGE and RAID. The bundled detector was fine-tuned on 70% of it; the ensembles on top learned from the other ${ensembleCount} texts. Each genre counts equally.`,
    '',
    'Each tier\'s model was chosen among logistic regressions and boosted trees by a criterion fixed in advance: the mean of (a) AUROC on each training genre (Yelp reviews, science writing, stories, business email and so on) when that genre is left out of training, and (b) AUROC on a held-out fifth of the training rows. Thresholds come from out-of-genre scores (each training genre scored by a model that never saw it): "likely AI" (80+) is set at 2% false alarms on that human text, "leans AI" (60+) at 10%. The evaluation sets below played no part in any choice.',
    '',
    ...TIERS.map((t) => `- **${t}**: ${chosen[t]}`),
    '',
    '**Tiers.** *Instant* (style statistics) shows while the models load. *Fast* adds the bundled fine-tuned detector, no download. *Classifier* adds the TMR RoBERTa detector. *Full* adds SmolLM2 perplexity, entropy and Binoculars scores.',
    '',
    '**Columns.** AUROC is threshold-free separation (50% = coin flip). *Caught* is the share of AI text scored 80+; *Caught 60+* adds "leans AI". *False alarms* is the share of human text scored 80+, *False alarms 60+* the share scored 60 or more.',
    '',
    '| Set | Texts | Method | AUROC | Caught | Caught 60+ | False alarms | False alarms 60+ |',
    '| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: |',
  ];
  for (const [set, rows] of Object.entries(evals)) {
    if (!rows.length) continue;
    const labels = rows.map((r) => r.label);
    const hasAi = labels.includes(1);
    const hasHuman = labels.includes(0);
    if (hasAi && hasHuman) for (const [name, f] of Object.entries(BASELINES)) lines.push(`| ${set} | ${rows.length} | ${name} | ${pct(auroc(rows.map(f), labels))} | | | | |`);
    for (const tier of TIERS) {
      if (tier === 'instant' && !set.startsWith('all modern')) continue;
      const m = set.startsWith('held-out') ? heldModels[tier] : models[tier];
      const p = rows.map((r) => probability(m, r.features));
      const share = (label: number, at: number) => rate(p.filter((_, i) => labels[i] === label).map((x) => x >= at));
      const cell = (show: boolean, v: () => number | null) => (show ? pct(v()) : '');
      lines.push(`| ${set} | ${rows.length} | **${tier}** | ${pct(auroc(p, labels))} | ${cell(hasAi, () => share(1, m.aiAt))} | ${cell(hasAi, () => share(1, m.leanAt))} | ${cell(hasHuman, () => share(0, m.aiAt))} | ${cell(hasHuman, () => share(0, m.leanAt))} |`);
    }
  }

  const modern = evals['modern AI (2025 chatbots)'] ?? [];
  if (modern.length) {
    lines.push('', '## 2025 chatbots by vendor and by request', '', 'Held-out LMArena and WildChat replies: no conversation here was used in training. *Humanize* is real users asking the chatbot to sound human or get past AI detectors. Each cell: share scored 80+ / share scored 60+.', '', '| Slice | Texts | Fast | Classifier | Full |', '| --- | ---: | ---: | ---: | ---: |');
    const slices: [string, (r: Row) => boolean][] = [
      ['all', () => true],
      ...[...new Set(modern.map((r) => r.meta!.split('/')[0]!))].sort().map((v): [string, (r: Row) => boolean] => [`vendor: ${v}`, (r) => r.meta!.startsWith(`${v}/`)]),
      ...[...new Set(modern.map((r) => r.meta!.split('/')[1]!))].sort().map((g): [string, (r: Row) => boolean] => [`request: ${g}`, (r) => r.meta!.split('/')[1] === g]),
    ];
    for (const [name, pred] of slices) {
      const rows = modern.filter(pred);
      if (rows.length >= 10) lines.push(`| ${name} | ${rows.length} | ${SHOWN.map((t) => both(t, rows)).join(' | ')} |`);
    }
  }

  const essays = evals['student essays (ELLIPSE, PERSUADE, AI)'] ?? [];
  if (essays.length) {
    lines.push('', '## Student essays', '', 'Held-out essays: ELLIPSE (English learners, grades 8-12), PERSUADE 2.0 (US grades 6-12, split by English-learner status), and Claude-written essays on the same kinds of prompts. Each cell: share scored 80+ / share scored 60+. For people lower is better; for AI higher is better.', '', '| Group | Texts | Fast | Classifier | Full |', '| --- | ---: | ---: | ---: | ---: |');
    const groups: [string, (r: Row) => boolean][] = [
      ['ELLIPSE learners (people)', (r) => r.meta!.startsWith('ellipse/')],
      ['PERSUADE English learners (people)', (r) => r.meta!.startsWith('persuade/ell/')],
      ['PERSUADE native speakers (people)', (r) => r.meta!.startsWith('persuade/native/')],
      ...['default', 'student', 'ell'].map((st): [string, (r: Row) => boolean] => [`Claude essays, ${st} style (AI)`, (r) => r.label === 1 && r.meta!.endsWith(`/${st}`)]),
    ];
    for (const [name, pred] of groups) {
      const rows = essays.filter(pred);
      if (rows.length) lines.push(`| ${name} | ${rows.length} | ${SHOWN.map((t) => both(t, rows)).join(' | ')} |`);
    }
  }

  const liang = evals['liang-nonnative'] ?? [];
  if (liang.length) {
    lines.push('', '## Non-native English writers', '', 'Liang et al. (2023) found commercial detectors flag TOEFL essays by non-native writers as AI far more often than essays by US students. None of these essays were used in training. GPTZero scores are from that study at its 0.5 cut-off. Our cells: share scored 80+ / share scored 60+.', '', '| Group | Texts | GPTZero flagged | Fast | Classifier | Full |', '| --- | ---: | ---: | ---: | ---: | ---: |');
    for (const src of [...new Set(liang.map((r) => r.source))]) {
      const rows = liang.filter((r) => r.source === src);
      const gz = rows.filter((r) => typeof r.gptzero?.score === 'number');
      const label = rows[0]!.label === 1 ? `${src} (AI: higher is better)` : `${src} (person: lower is better)`;
      lines.push(`| ${label} | ${rows.length} | ${gz.length ? pct(rate(gz.map((r) => r.gptzero!.score! >= 0.5))) : '–'} | ${SHOWN.map((t) => both(t, rows)).join(' | ')} |`);
    }
  }
  const adv = evals['raid-adversarial'] ?? [];
  if (adv.length) {
    lines.push('', '## By attack (RAID)', '', 'AUROC per attack. About 15 human and 15 AI texts each, so read these as directional.', '', '| Attack | Fast | Classifier | Full |', '| --- | ---: | ---: | ---: |');
    for (const a of [...new Set(adv.map((r) => r.meta!.split('/')[2]!))].sort()) {
      const rows = adv.filter((r) => r.meta!.endsWith(`/${a}`));
      const au = (t: TierName) => pct(auroc(rows.map((r) => probability(models[t], r.features)), rows.map((r) => r.label)));
      lines.push(`| ${a} | ${au('fast')} | ${au('classifier')} | ${au('full')} |`);
    }
  }
  const dom = evals['domain-ai'] ?? [];
  if (dom.length) {
    lines.push('', '## Modern in-domain AI text', '', 'The original 90-text set: sales emails, LinkedIn posts, marketing copy and docs written by Claude Opus, Sonnet and Haiku, from prompts separate from all training samples. Half were told to sound human. Each cell: share scored 80+ / share scored 60+.', '', '| Slice | Texts | Fast | Classifier | Full |', '| --- | ---: | ---: | ---: | ---: |');
    const slices: [string, (r: Row) => boolean][] = [
      ['all', () => true],
      ['default style', (r) => r.meta!.endsWith('/default')],
      ['told to sound human', (r) => r.meta!.endsWith('/humanlike')],
      ['Opus (no Opus text in training)', (r) => r.meta!.startsWith('claude-opus/')],
      ...['outreach', 'content', 'marketing', 'docs'].map((p): [string, (r: Row) => boolean] => [p, (r) => r.meta!.split('/')[1] === p]),
    ];
    for (const [name, pred] of slices) {
      const rows = dom.filter(pred);
      lines.push(`| ${name} | ${rows.length} | ${SHOWN.map((t) => both(t, rows)).join(' | ')} |`);
    }
  }
  lines.push('', '## Limits', '',
    '- No detector is proof of authorship. Treat a high score as a reason to look closer, never as a verdict about a person.',
    '- Under 50 words the extension shows no score; under 150 it marks the score low-confidence.',
    '- Heavily edited AI text, and human text polished by AI, legitimately land in the middle.',
    '- RAID is part of TMR\'s training data, so RAID rows are in-distribution for the classifier. The other evaluation sets are not.',
    '- Sets of about 1,000 texts give percentages within about ±3 points; the 90-text Claude set within about ±10.',
    '- Human marketing copy has no licensed pre-2022 source here, so false alarms on marketing copy are not measured.',
    '- Student essays: see the student-essay and non-native tables before relying on a score for school work.', '');
  await writeFile('docs/detection-eval.md', lines.join('\n'));
  console.log(lines.slice(lines.indexOf('| Set | Texts | Method | AUROC | Caught | Caught 60+ | False alarms | False alarms 60+ |')).join('\n'));
}
